ZERO_ASI = {"str": 0, "dex": 0, "con": 0, "int": 0, "wis": 0, "cha": 0}


def asi(str_=0, dex=0, con=0, int_=0, wis=0, cha=0):
    return {"str": str_, "dex": dex, "con": con, "int": int_, "wis": wis, "cha": cha}


def clean_text(value: str) -> str:
    return re.sub(r"\s+", " ", (value or "").replace("\xa0", " ")).strip()


def clean_title(value: str) -> str:
    title = clean_text(value).rstrip(".:")
    title = title.replace("Увеличение характеристики", "Увеличение характеристик")
    if title == "Иммун":
        return "Иммунитет к яду"
    if title == "П":
        return "Помеченная цель"
    return title


def ordered_traits(pairs):
    traits = OrderedDict()
    for title, text in pairs:
        title = clean_title(title)
        text = clean_text(text)
        if title and text:
            traits[title] = text
    return traits


def trait_value(race, title, fallback=""):
    traits = race.get("traits", {})
    for key, value in traits.items():
        if clean_title(key).lower() == title.lower():
            return clean_text(value)
    return fallback


def normalize_trait_map(traits):
    result = OrderedDict()
    noise_prefixes = (
        "мужск",
        "женск",
        "детск",
        "фамил",
        "названия",
        "название",
        "прозвищ",
        "кланы",
        "лидер",
        "штаб",
        "смотрите статью",
        "о дварфах",
        "об эльфах",
        "о полуросликах",
        "о людях",
        "модификатор размера",
        "высота",
        "вес в фунтах",
        "разновидности",
        "подраса",
    )
    noise_exact = {
        "Хазлан",
        "Картакасс",
        "Тепест",
        "Хар’Акир",
        "Ламордия",
        "Мордент",
        "Баровия",
        "Даркон",
        "И'Кат",
        "Внешний вид",
    }

    for raw_title, raw_text in traits.items():
        title = clean_title(raw_title)
        text = clean_text(raw_text)
        lowered = title.lower()
        if not title or not text:
            continue
        if title in noise_exact or any(lowered.startswith(prefix) for prefix in noise_prefixes):
            continue
        if title == "Иммунитет к яду" and text.startswith("итет к яду"):
            text = "Вы обладаете иммунитетом к урону ядом и состоянию отравленный."
        if title == "Помеченная цель" and text.startswith("омеченная цель"):
            text = "Бонусным действием вы можете пометить одно существо, которое вы можете видеть в пределах 10 футов. До конца вашего следующего продолжительного отдыха ваш бонус мастерства удваивается при попытке выследить эту цель, а также вы всегда знаете точное местоположение цели, если она находится в пределах 60 футов от вас. Вы не можете использовать эту особенность повторно, пока не закончите короткий или продолжительный отдых."
        if title not in result:
            result[title] = text
    return result


def base_traits_from_existing(race, allowed):
    normalized = normalize_trait_map(race.get("traits", {}))
    return ordered_traits((title, normalized.get(title, trait_value(race, title))) for title in allowed)


