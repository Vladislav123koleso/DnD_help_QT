def normalize_entry(race):
    race = OrderedDict(race)
    name = race.get("name", "")
    race.setdefault("type", "subrace" if name in SUBRACE_NAMES else "race")
    if name in SUBRACE_NAMES:
        race["type"] = "subrace"
    else:
        race["type"] = "race"

    race.setdefault("flyingSpeed", 0)
    race.setdefault("speed", 30)
    race.setdefault("size", "Средний")
    race.setdefault("asi", dict(ZERO_ASI))
    race.setdefault("traits", {})
    race.setdefault("languages", [])

    race["traits"] = normalize_trait_map(race.get("traits", {}))
    race = apply_curated_base(race)

    if name in SIZE_OVERRIDES:
        race["size"] = SIZE_OVERRIDES[name]
    if name in FLYING_SPEED_FROM_WALKING:
        race["flyingSpeed"] = race.get("speed", 30)
    if name in LANGUAGE_OVERRIDES:
        race["languages"] = LANGUAGE_OVERRIDES[name]
    if name in SUBRACE_DESCRIPTIONS:
        race["description"] = SUBRACE_DESCRIPTIONS[name]

    if name == "Кованый":
        race["asi"] = asi(con=2)
    elif name == "Гоблин":
        race["asi"] = asi(dex=2, con=1)
    elif name == "Голиаф":
        race["asi"] = asi(str_=2, con=1)
    elif name == "Грунг":
        race["asi"] = asi(dex=2, con=1)
    elif name == "Минотавр":
        race["asi"] = asi(str_=2, con=1)
    elif name == "Орк":
        race["asi"] = asi(str_=2, con=1)
    elif name == "Полуорк":
        race["asi"] = asi(str_=2, con=1)
    elif name == "Кентавр":
        race["asi"] = asi(str_=2, wis=1)
    elif name == "Тритон":
        race["asi"] = asi(str_=1, con=1, cha=1)
    elif name == "Человек":
        race["asi"] = asi(str_=1, dex=1, con=1, int_=1, wis=1, cha=1)
    elif name == "Полуэльф":
        race["asi"] = asi(cha=2)
    elif name == "Тифлинг":
        race["asi"] = asi(int_=1, cha=2)

    return race


def main():
    races = json.loads(RACES_PATH.read_text(encoding="utf-8"), object_pairs_hook=OrderedDict)
    inserted_names = set(SUBRACE_NAMES)
    normalized = []

    for race in races:
        name = race.get("name", "")
        if name in inserted_names and name in {sub["name"] for group in SUBRACES_TO_INSERT.values() for sub in group}:
            continue

        normalized_race = normalize_entry(race)
        normalized.append(normalized_race)

        for sub in SUBRACES_TO_INSERT.get(name, []):
            sub = OrderedDict(sub)
            sub_name = sub.get("name", "")
            if sub_name in SUBRACE_DESCRIPTIONS:
                sub["description"] = SUBRACE_DESCRIPTIONS[sub_name]
            normalized.append(OrderedDict(sub))

    RACES_PATH.write_text(json.dumps(normalized, ensure_ascii=False, indent=2), encoding="utf-8")

    subrace_map = OrderedDict(
        [
            ("Аасимар", ["Аасимар-Защитник", "Аасимар-Каратель", "Падший Аасимар"]),
            ("Гит", ["Гитцерай", "Гитьянки"]),
            ("Гном", ["Лесной гном", "Скальный гном"]),
            ("Дварф", ["Холмовой дварф", "Горный дварф"]),
            ("Дженази", ["Дженази воздуха", "Дженази земли", "Дженази огня", "Дженази воды"]),
            ("Полурослик", ["Легконогий полурослик", "Коренастый полурослик"]),
            ("Шифтер", ["Шифтер-зверокожий", "Шифтер-длиннозубый", "Шифтер-быстроход", "Шифтер-дикоохотник"]),
            ("Эльф", ["Высший эльф", "Лесной эльф", "Дроу", "Гругач"]),
        ]
    )
    SUBRACES_PATH.write_text(json.dumps(subrace_map, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"Normalized {len(normalized)} races/subraces")


