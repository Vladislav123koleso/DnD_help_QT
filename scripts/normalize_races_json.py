def subrace(name, source, description, speed=None, size=None, flying_speed=None, asi_values=None, traits=None, languages=None):
    race = {
        "name": name,
        "type": "subrace",
        "source": source,
        "description": description,
        "asi": asi_values or dict(ZERO_ASI),
        "traits": traits or {},
    }
    if speed is not None:
        race["speed"] = speed
    if size is not None:
        race["size"] = size
    if flying_speed is not None:
        race["flyingSpeed"] = flying_speed
    if languages is not None:
        race["languages"] = languages
    return race


